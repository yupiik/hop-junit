package io.yupiik.hop.junit.database.h2.driver;

import java.math.BigInteger;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/**
 * Rewrites Oracle DDL that H2 (in Oracle mode) rejects into an equivalent H2 statement.
 *
 * <p>Only {@code CREATE}, {@code ALTER} and {@code DROP} statements are touched. The rewrite is
 * token based so literals, quoted identifiers and comments are never altered:
 *
 * <ul>
 *   <li>physical/storage attributes are dropped ({@code TABLESPACE x}, {@code PCTFREE n},
 *       {@code PCTUSED n}, {@code INITRANS n}, {@code MAXTRANS n}, {@code STORAGE (...)},
 *       {@code [NO]LOGGING}, {@code [NO]COMPRESS [...]}, {@code [NO]PARALLEL [n]},
 *       {@code SEGMENT CREATION IMMEDIATE|DEFERRED}, {@code [NO]MONITORING},
 *       {@code [NO]ROWDEPENDENCIES}, table level {@code CACHE}/{@code NOCACHE}, {@code USING INDEX [...]}
 *       and constraint states {@code ENABLE}/{@code DISABLE}/{@code VALIDATE}/{@code NOVALIDATE});</li>
 *   <li>{@code DROP ... PURGE} loses its {@code PURGE};</li>
 *   <li>types: {@code NUMBER(*,s)} becomes {@code NUMBER(38,s)}, {@code WITH LOCAL TIME ZONE}
 *       becomes {@code WITH TIME ZONE}, {@code FLOAT(p)} with a binary precision above 53 becomes
 *       {@code FLOAT(53)}, {@code LONG} becomes {@code CLOB} ({@code LONG RAW} becomes {@code BLOB}), {@code XMLTYPE} becomes {@code CLOB}, {@code ROWID}/{@code UROWID} become
 *       {@code VARCHAR2(4000)};</li>
 *   <li>identity/defaults: {@code GENERATED BY DEFAULT ON NULL AS IDENTITY} loses {@code ON NULL};</li>
 *   <li>sequences: {@code ORDER}/{@code NOORDER} and {@code NOKEEP}/{@code KEEP}/{@code NOSCALE} are
 *       dropped and a {@code MAXVALUE} beyond the H2 {@code BIGINT} range is clamped;</li>
 *   <li>temporary tables: {@code ON COMMIT PRESERVE ROWS} is dropped (it is the H2 default).</li>
 * </ul>
 *
 * <p>Length semantics ({@code VARCHAR2(n CHAR|BYTE)}), {@code LONG}, {@code BINARY_DOUBLE},
 * {@code BINARY_FLOAT}, {@code RAW(n)} and sequence {@code NOCACHE} are natively accepted by H2 so they
 * are kept as is.
 */
public class OracleDdlRewriter {
    private static final Set<String> SINGLE_KEYWORDS = Set.of(
            "LOGGING",
            "NOLOGGING",
            "NOCOMPRESS",
            "NOPARALLEL",
            "MONITORING",
            "NOMONITORING",
            "ROWDEPENDENCIES",
            "NOROWDEPENDENCIES",
            "ENABLE",
            "DISABLE",
            "VALIDATE",
            "NOVALIDATE");
    private static final Set<String> KEYWORD_WITH_VALUE =
            Set.of("TABLESPACE", "PCTFREE", "PCTUSED", "INITRANS", "MAXTRANS");
    private static final Set<String> SEQUENCE_KEYWORDS = Set.of("ORDER", "NOORDER", "KEEP", "NOKEEP", "NOSCALE");
    private static final BigInteger MAX_BIGINT = BigInteger.valueOf(Long.MAX_VALUE);
    private static final BigInteger MIN_BIGINT = BigInteger.valueOf(Long.MIN_VALUE);

    public OracleDdlRewriter() {
        // no-op
    }

    /**
     * Rewrites a DDL statement, returns it unchanged when it is not a DDL or when nothing needs a rewrite.
     *
     * @param sql the statement
     * @return the H2 compatible statement
     */
    public String rewrite(final String sql) {
        final var tokens = OracleSql.tokens(sql);
        if (tokens.isEmpty()) {
            return sql;
        }
        final var first = tokens.getFirst();
        if (!first.is("CREATE") && !first.is("ALTER") && !first.is("DROP")) {
            return sql;
        }
        final var edits = new ArrayList<Edit>();
        final var sequence = isSequence(tokens);
        for (var i = 1; i < tokens.size(); i++) {
            final var token = tokens.get(i);
            if (token.literal()) {
                continue;
            }
            final var upper = token.text().toUpperCase(java.util.Locale.ROOT);
            if (sequence) {
                i = sequence(tokens, i, upper, edits);
                continue;
            }
            if (first.is("DROP") && "PURGE".equals(upper) && i == tokens.size() - 1) {
                edits.add(remove(tokens, i, i));
                continue;
            }
            switch (upper) {
                case "TABLESPACE", "PCTFREE", "PCTUSED", "INITRANS", "MAXTRANS" -> {
                    if (i + 1 < tokens.size() && !isEnd(tokens.get(i + 1))) {
                        edits.add(remove(tokens, i, i + 1));
                        i++;
                    }
                }
                case "STORAGE" -> {
                    if (i + 1 < tokens.size() && tokens.get(i + 1).is("(")) {
                        final var close = closing(tokens, i + 1);
                        edits.add(remove(tokens, i, close));
                        i = close;
                    }
                }
                case "COMPRESS" -> {
                    var end = i;
                    if (i + 1 < tokens.size() && (tokens.get(i + 1).is("BASIC") || isNumber(tokens.get(i + 1)))) {
                        end = i + 1;
                    } else if (i + 2 < tokens.size()
                            && (tokens.get(i + 1).is("FOR") || tokens.get(i + 1).is("ADVANCED"))) {
                        end = i + 1;
                        while (end + 1 < tokens.size() && !isEnd(tokens.get(end + 1)) && isWord(tokens.get(end + 1))) {
                            end++;
                        }
                    }
                    edits.add(remove(tokens, i, end));
                    i = end;
                }
                case "PARALLEL" -> {
                    final var end = i + 1 < tokens.size() && isNumber(tokens.get(i + 1)) ? i + 1 : i;
                    edits.add(remove(tokens, i, end));
                    i = end;
                }
                case "SEGMENT" -> {
                    if (i + 2 < tokens.size() && tokens.get(i + 1).is("CREATION")) {
                        edits.add(remove(tokens, i, i + 2));
                        i += 2;
                    }
                }
                case "CACHE", "NOCACHE" -> {
                    // table level only (sequences are handled separately): after the column list
                    if (afterTopLevelParenthesis(tokens, i)) {
                        edits.add(remove(tokens, i, i));
                    }
                }
                case "USING" -> {
                    if (i + 1 < tokens.size() && tokens.get(i + 1).is("INDEX")) {
                        var end = i + 1;
                        if (end + 1 < tokens.size() && tokens.get(end + 1).is("(")) {
                            end = closing(tokens, end + 1);
                        } else {
                            while (end + 1 < tokens.size() && isPhysicalAttribute(tokens, end + 1)) {
                                end = skipPhysicalAttribute(tokens, end + 1);
                            }
                        }
                        edits.add(remove(tokens, i, end));
                        i = end;
                    }
                }
                case "LOGGING",
                        "NOLOGGING",
                        "NOCOMPRESS",
                        "NOPARALLEL",
                        "MONITORING",
                        "NOMONITORING",
                        "ROWDEPENDENCIES",
                        "NOROWDEPENDENCIES" -> edits.add(remove(tokens, i, i));
                case "ENABLE", "DISABLE", "VALIDATE", "NOVALIDATE" -> {
                    // constraint state; ALTER TABLE ... ENABLE/DISABLE CONSTRAINT x is kept (H2 rejects it anyway)
                    if (!(i + 1 < tokens.size()
                            && (tokens.get(i + 1).is("CONSTRAINT")
                                    || tokens.get(i + 1).is("ALL")))) {
                        edits.add(remove(tokens, i, i));
                    }
                }
                case "PRESERVE" -> {
                    if (i >= 2
                            && tokens.get(i - 1).is("COMMIT")
                            && tokens.get(i - 2).is("ON")
                            && i + 1 < tokens.size()
                            && tokens.get(i + 1).is("ROWS")) {
                        edits.add(remove(tokens, i - 2, i + 1));
                        i++;
                    }
                }
                case "NUMBER" -> {
                    if (i + 2 < tokens.size()
                            && tokens.get(i + 1).is("(")
                            && tokens.get(i + 2).is("*")) {
                        edits.add(new Edit(
                                tokens.get(i + 2).start(), tokens.get(i + 2).end(), "38"));
                        i += 2;
                    }
                }
                case "FLOAT" -> {
                    if (i + 3 < tokens.size()
                            && tokens.get(i + 1).is("(")
                            && isNumber(tokens.get(i + 2))
                            && tokens.get(i + 3).is(")")
                            && new BigInteger(tokens.get(i + 2).text()).intValue() > 53) {
                        edits.add(new Edit(
                                tokens.get(i + 2).start(), tokens.get(i + 2).end(), "53"));
                        i += 3;
                    }
                }
                case "LOCAL" -> {
                    if (i >= 1
                            && tokens.get(i - 1).is("WITH")
                            && i + 2 < tokens.size()
                            && tokens.get(i + 1).is("TIME")
                            && tokens.get(i + 2).is("ZONE")) {
                        edits.add(remove(tokens, i, i));
                    }
                }
                case "LONG" -> {
                    // H2 Oracle mode maps LONG to BIGINT while Oracle LONG is character data
                    if (isColumnType(tokens, i)) {
                        if (i + 1 < tokens.size() && tokens.get(i + 1).is("RAW")) {
                            edits.add(new Edit(token.start(), tokens.get(i + 1).end(), "BLOB"));
                            i++;
                        } else {
                            edits.add(new Edit(token.start(), token.end(), "CLOB"));
                        }
                    }
                }
                case "XMLTYPE" -> {
                    if (isColumnType(tokens, i)) {
                        edits.add(new Edit(token.start(), token.end(), "CLOB"));
                    }
                }
                case "ROWID", "UROWID" -> {
                    if (isColumnType(tokens, i)) {
                        var end = i;
                        if (i + 3 < tokens.size()
                                && tokens.get(i + 1).is("(")
                                && tokens.get(i + 3).is(")")) {
                            end = i + 3;
                        }
                        edits.add(new Edit(token.start(), tokens.get(end).end(), "VARCHAR2(4000)"));
                        i = end;
                    }
                }
                case "ON" -> {
                    // GENERATED BY DEFAULT ON NULL AS IDENTITY: H2 expects "... AS IDENTITY [(...)] DEFAULT ON NULL"
                    if (i >= 3
                            && tokens.get(i - 1).is("DEFAULT")
                            && tokens.get(i - 2).is("BY")
                            && tokens.get(i - 3).is("GENERATED")
                            && i + 3 < tokens.size()
                            && tokens.get(i + 1).is("NULL")
                            && tokens.get(i + 2).is("AS")
                            && tokens.get(i + 3).is("IDENTITY")) {
                        edits.add(remove(tokens, i, i + 1));
                        var identityEnd = i + 3;
                        if (identityEnd + 1 < tokens.size()
                                && tokens.get(identityEnd + 1).is("(")) {
                            identityEnd = closing(tokens, identityEnd + 1);
                        }
                        final var at = tokens.get(identityEnd).end();
                        edits.add(new Edit(at, at, " DEFAULT ON NULL"));
                        i = identityEnd;
                    }
                }
                default -> {
                    // no-op
                }
            }
        }
        return apply(sql, edits);
    }

    private int sequence(final List<OracleSql.Token> tokens, final int i, final String upper, final List<Edit> edits) {
        if (SEQUENCE_KEYWORDS.contains(upper)) {
            edits.add(remove(tokens, i, i));
            return i;
        }
        if (("MAXVALUE".equals(upper) || "MINVALUE".equals(upper)) && i + 1 < tokens.size()) {
            var valueIndex = i + 1;
            var negative = false;
            if (tokens.get(valueIndex).is("-") && valueIndex + 1 < tokens.size()) {
                negative = true;
                valueIndex++;
            }
            final var value = tokens.get(valueIndex);
            if (isNumber(value)) {
                final var number = negative ? new BigInteger(value.text()).negate() : new BigInteger(value.text());
                if (number.compareTo(MAX_BIGINT) > 0 || number.compareTo(MIN_BIGINT) < 0) {
                    edits.add(new Edit(
                            tokens.get(i + 1).start(),
                            value.end(),
                            (number.signum() > 0 ? MAX_BIGINT : MIN_BIGINT).toString()));
                }
                return valueIndex;
            }
        }
        return i;
    }

    private boolean isSequence(final List<OracleSql.Token> tokens) {
        for (var i = 1; i < Math.min(tokens.size(), 4); i++) {
            if (tokens.get(i).is("SEQUENCE")) {
                return true;
            }
        }
        return false;
    }

    private boolean isPhysicalAttribute(final List<OracleSql.Token> tokens, final int index) {
        final var token = tokens.get(index);
        if (token.literal()) {
            return false;
        }
        final var upper = token.text().toUpperCase(java.util.Locale.ROOT);
        return KEYWORD_WITH_VALUE.contains(upper)
                || SINGLE_KEYWORDS.contains(upper)
                || "STORAGE".equals(upper)
                || "COMPRESS".equals(upper)
                || "PARALLEL".equals(upper);
    }

    private int skipPhysicalAttribute(final List<OracleSql.Token> tokens, final int index) {
        final var upper = tokens.get(index).text().toUpperCase(java.util.Locale.ROOT);
        if (KEYWORD_WITH_VALUE.contains(upper)) {
            return Math.min(index + 1, tokens.size() - 1);
        }
        if ("STORAGE".equals(upper)
                && index + 1 < tokens.size()
                && tokens.get(index + 1).is("(")) {
            return closing(tokens, index + 1);
        }
        if (("COMPRESS".equals(upper) || "PARALLEL".equals(upper))
                && index + 1 < tokens.size()
                && isNumber(tokens.get(index + 1))) {
            return index + 1;
        }
        return index;
    }

    // a column type is preceded by the column name, itself preceded by "(" or ","
    // (or by ADD/MODIFY in ALTER TABLE)
    private boolean isColumnType(final List<OracleSql.Token> tokens, final int index) {
        if (index < 2) {
            return false;
        }
        final var before = tokens.get(index - 2);
        return before.is("(") || before.is(",") || before.is("ADD") || before.is("MODIFY");
    }

    private boolean afterTopLevelParenthesis(final List<OracleSql.Token> tokens, final int index) {
        var depth = 0;
        var sawParenthesis = false;
        for (var i = 0; i < index; i++) {
            if (tokens.get(i).is("(")) {
                depth++;
                sawParenthesis = true;
            } else if (tokens.get(i).is(")")) {
                depth--;
            }
        }
        return sawParenthesis && depth == 0;
    }

    private int closing(final List<OracleSql.Token> tokens, final int open) {
        var depth = 0;
        for (var i = open; i < tokens.size(); i++) {
            if (tokens.get(i).is("(")) {
                depth++;
            } else if (tokens.get(i).is(")") && --depth == 0) {
                return i;
            }
        }
        return tokens.size() - 1;
    }

    private boolean isEnd(final OracleSql.Token token) {
        return token.is(")") || token.is(",") || token.is(";");
    }

    private boolean isWord(final OracleSql.Token token) {
        return !token.literal()
                && !token.text().isEmpty()
                && Character.isLetter(token.text().charAt(0));
    }

    private boolean isNumber(final OracleSql.Token token) {
        return !token.literal()
                && token.text().chars().allMatch(Character::isDigit)
                && !token.text().isEmpty();
    }

    private Edit remove(final List<OracleSql.Token> tokens, final int from, final int to) {
        return new Edit(tokens.get(from).start(), tokens.get(to).end(), "");
    }

    private String apply(final String sql, final List<Edit> edits) {
        if (edits.isEmpty()) {
            return sql;
        }
        final var out = new StringBuilder(sql.length());
        var last = 0;
        for (final var edit : edits) {
            if (edit.start() < last) {
                continue;
            }
            out.append(sql, last, edit.start()).append(edit.replacement());
            last = edit.end();
            if (edit.replacement().isEmpty()
                    && !out.isEmpty()
                    && Character.isWhitespace(out.charAt(out.length() - 1))) {
                while (last < sql.length() && Character.isWhitespace(sql.charAt(last))) {
                    last++;
                }
            }
        }
        return out.append(sql, last, sql.length())
                .toString()
                .replaceAll("[ \\t]+(?=[,)])", "")
                .stripTrailing();
    }

    private record Edit(int start, int end, String replacement) {}
}
