package io.yupiik.hop.junit.database.h2;

import static org.junit.jupiter.api.Assertions.assertEquals;

import io.yupiik.hop.junit.database.h2.driver.H2SqlRewriteDriver;
import io.yupiik.hop.junit.database.h2.driver.OracleDdlRewriter;
import java.sql.DriverManager;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

class OracleDdlRewriterTest {
    private final OracleDdlRewriter rewriter = new OracleDdlRewriter();

    @ParameterizedTest
    @CsvSource(
            delimiter = '|',
            value = {
                "CREATE TABLE T (A NUMBER) TABLESPACE USERS|CREATE TABLE T (A NUMBER)",
                "CREATE TABLE T (A NUMBER) NOLOGGING PCTFREE 10 INITRANS 2|CREATE TABLE T (A NUMBER)",
                "CREATE TABLE T (A NUMBER) STORAGE (INITIAL 64K NEXT 1M) COMPRESS PARALLEL 4|CREATE TABLE T (A NUMBER)",
                "CREATE TABLE T (A NUMBER) SEGMENT CREATION IMMEDIATE LOGGING NOCACHE|CREATE TABLE T (A NUMBER)",
                "CREATE TABLE T (A NUMBER(*,0))|CREATE TABLE T (A NUMBER(38,0))",
                "CREATE TABLE T (A TIMESTAMP WITH LOCAL TIME ZONE)|CREATE TABLE T (A TIMESTAMP WITH TIME ZONE)",
                "CREATE TABLE T (A FLOAT(126), B FLOAT(10))|CREATE TABLE T (A FLOAT(53), B FLOAT(10))",
                "CREATE TABLE T (A XMLTYPE, B ROWID, C UROWID(100))|CREATE TABLE T (A CLOB, B VARCHAR2(4000), C VARCHAR2(4000))",
                "CREATE TABLE T (ID NUMBER, A LONG, B LONG RAW)|CREATE TABLE T (ID NUMBER, A CLOB, B BLOB)",
                "ALTER TABLE T ADD A LONG|ALTER TABLE T ADD A CLOB",
                "CREATE TABLE T (A NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY)|CREATE TABLE T (A NUMBER GENERATED BY DEFAULT AS IDENTITY DEFAULT ON NULL)",
                "CREATE TABLE T (A NUMBER, CONSTRAINT T_PK PRIMARY KEY (A) USING INDEX TABLESPACE USERS ENABLE)|CREATE TABLE T (A NUMBER, CONSTRAINT T_PK PRIMARY KEY (A))",
                "CREATE GLOBAL TEMPORARY TABLE T (A NUMBER) ON COMMIT PRESERVE ROWS|CREATE GLOBAL TEMPORARY TABLE T (A NUMBER)",
                "CREATE INDEX I ON T (A) TABLESPACE USERS NOLOGGING|CREATE INDEX I ON T (A)",
                "CREATE SEQUENCE S START WITH 1 NOCYCLE NOORDER CACHE 20|CREATE SEQUENCE S START WITH 1 NOCYCLE CACHE 20",
                "CREATE SEQUENCE S MINVALUE 1 MAXVALUE 9999999999999999999999999999 NOCACHE|CREATE SEQUENCE S MINVALUE 1 MAXVALUE 9223372036854775807 NOCACHE",
                "DROP TABLE T PURGE|DROP TABLE T",
                "DROP TABLE T CASCADE CONSTRAINTS PURGE|DROP TABLE T CASCADE CONSTRAINTS",
                "CREATE TABLE T (A VARCHAR2(10 CHAR), B LONG, C BINARY_DOUBLE, D RAW(16))|CREATE TABLE T (A VARCHAR2(10 CHAR), B CLOB, C BINARY_DOUBLE, D RAW(16))",
                "CREATE TABLE T (A VARCHAR2(20) DEFAULT 'TABLESPACE USERS')|CREATE TABLE T (A VARCHAR2(20) DEFAULT 'TABLESPACE USERS')",
                "SELECT 'TABLESPACE' FROM DUAL|SELECT 'TABLESPACE' FROM DUAL"
            })
    void rewrites(final String oracle, final String h2) {
        assertEquals(h2, rewriter.rewrite(oracle));
    }

    @Test
    void rewrittenDdlRunsOnH2() throws Exception {
        final var driver = new H2SqlRewriteDriver();
        try (final var connection = DriverManager.getConnection(
                        driver.wrap("jdbc:h2:mem:ddl;MODE=Oracle;DATABASE_TO_UPPER=true"), "sa", "");
                final var statement = connection.createStatement()) {
            for (final var ddl : new String[] {
                "CREATE TABLE T1 (ID NUMBER(*,0), LABEL VARCHAR2(40 CHAR), BODY LONG, AMOUNT BINARY_DOUBLE, "
                        + "TS TIMESTAMP WITH LOCAL TIME ZONE, X XMLTYPE, R ROWID, F FLOAT(126), "
                        + "CONSTRAINT T1_PK PRIMARY KEY (ID) USING INDEX TABLESPACE USERS ENABLE) "
                        + "SEGMENT CREATION IMMEDIATE PCTFREE 10 NOLOGGING STORAGE (INITIAL 64K) TABLESPACE USERS",
                "CREATE TABLE T2 (ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY, V VARCHAR2(3)) COMPRESS PARALLEL 2",
                "CREATE INDEX T2_V ON T2 (V) TABLESPACE USERS NOLOGGING",
                "CREATE GLOBAL TEMPORARY TABLE T3 (A NUMBER) ON COMMIT PRESERVE ROWS",
                "CREATE SEQUENCE S1 START WITH 10 INCREMENT BY 5 MAXVALUE 9999999999999999999999999999 NOCYCLE NOORDER NOCACHE",
                "DROP TABLE T3 PURGE"
            }) {
                statement.execute(ddl);
            }
            statement.execute("INSERT INTO T2 (ID, V) VALUES (NULL, 'a')");
            statement.execute("INSERT INTO T1 (ID, BODY) VALUES (1, 'legacy text')");
            try (final var result = statement.executeQuery("SELECT BODY FROM T1")) {
                result.next();
                assertEquals("legacy text", result.getString(1));
            }
            try (final var result = statement.executeQuery("SELECT S1.NEXTVAL FROM DUAL")) {
                result.next();
                assertEquals(10, result.getInt(1));
            }
        }
    }
}
