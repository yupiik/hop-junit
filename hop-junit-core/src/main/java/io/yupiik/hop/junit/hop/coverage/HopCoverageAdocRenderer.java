package io.yupiik.hop.junit.hop.coverage;

import io.yupiik.hop.junit.hop.coverage.HopCoverageModels.AggregateReport;
import io.yupiik.hop.junit.hop.coverage.HopCoverageModels.ArtifactReport;
import io.yupiik.hop.junit.hop.coverage.HopCoverageModels.Edge;
import io.yupiik.hop.junit.hop.coverage.HopCoverageModels.Node;
import io.yupiik.hop.junit.hop.coverage.HopCoverageModels.Ratio;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.text.MessageFormat;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.ResourceBundle;

/**
 * Renders the aggregate coverage report as an AsciiDoc document using localized messages (see
 * {@code HopCoverageAdocRenderer_<locale>.properties}), honoring the expected-coverage threshold from
 * the {@link HopCoverageConfig}.
 */
public final class HopCoverageAdocRenderer {
    private static final double DEFAULT_EXPECTED_COVERAGE = 80d;

    private final HopCoverageConfig config;
    private final ResourceBundle messages;

    public HopCoverageAdocRenderer(final HopCoverageConfig config) {
        this.config = config;
        this.messages = ResourceBundle.getBundle(
                HopCoverageAdocRenderer.class.getName(),
                switch (config.adocReport().language()) {
                    case FR -> Locale.FRENCH;
                    case EN -> Locale.ENGLISH;
                });
    }

    public void write(final AggregateReport report) throws IOException {
        final var output = config.adocReport().output();
        Files.createDirectories(output.getParent());
        Files.writeString(output, render(report));
    }

    private String render(final AggregateReport report) {
        final var artifacts = report.artifacts().stream()
                .sorted(Comparator.comparing(
                                (ArtifactReport it) -> it.artifact().kind())
                        .thenComparing(it -> it.artifact().path()))
                .toList();
        final var adoc = new StringBuilder(64_000);
        adoc.append("// Generated by Hop coverage. Do not edit manually.\n\n")
                .append("== ")
                .append(text(config.adocReport().title()))
                .append("\n\n");
        if (config.adocReport().description() != null
                && !config.adocReport().description().isBlank()) {
            adoc.append(text(config.adocReport().description())).append("\n\n");
        }
        adoc.append(MessageFormat.format(messages.getString("reportGenerated"), text(report.generatedAt())))
                .append("\n")
                .append(MessageFormat.format(
                        messages.getString("consolidates"),
                        report.executions().size(),
                        report.artifacts().size()))
                .append("\n")
                .append(MessageFormat.format(
                        messages.getString("defaultThreshold"), percentValue(expectedCoverage() * 100)))
                .append("\n\n");
        summary(adoc, report);
        coverageSemantics(adoc);
        // Glossary / definitions: explain what we report (nodes, edges, arcs)
        adoc.append("=== ")
                .append(messages.getString("glossaryHeading"))
                .append("\n\n")
                .append(messages.getString("glossaryNode"))
                .append("\n\n")
                .append(messages.getString("glossaryEdge"))
                .append("\n\n")
                .append(messages.getString("glossaryHop"))
                .append("\n\n");
        aggregateTable(adoc, artifacts);
        artifactDetails(adoc, artifacts);
        return adoc.toString();
    }

    private void summary(final StringBuilder adoc, final AggregateReport report) {
        adoc.append("=== ")
                .append(messages.getString("summaryHeading"))
                .append("\n\n")
                .append("[cols=\"2,1,1,1\",opts=\"headers\"]\n|===\n")
                .append(messages.getString("summaryHeader"))
                .append('\n');
        ratio(adoc, messages.getString("metricNodes"), report.summary().nodes());
        ratio(adoc, messages.getString("metricEdges"), report.summary().edges());
        ratio(adoc, messages.getString("metricBranches"), report.summary().branches());
        adoc.append("|===\n\n");
    }

    private void coverageSemantics(final StringBuilder adoc) {
        adoc.append("[NOTE]\n")
                .append("====\n")
                .append(messages.getString("semanticsPipeline"))
                .append('\n')
                .append(messages.getString("semanticsWorkflow"))
                .append('\n')
                .append("====\n\n");
    }

    private void aggregateTable(final StringBuilder adoc, final List<ArtifactReport> artifacts) {
        adoc.append("=== ")
                .append(messages.getString("coverageByArtifactHeading"))
                .append("\n\n")
                .append("[cols=\"1,1,3,1,1,1,1,1\",opts=\"headers\"]\n|===\n")
                .append(messages.getString("coverageByArtifactHeader"))
                .append('\n');
        for (final var artifact : artifacts) {
            adoc.append('|')
                    .append(status(artifact))
                    .append('\n')
                    .append('|')
                    .append(text(artifact.artifact().kind()))
                    .append('\n')
                    .append('|')
                    .append(link(artifact))
                    .append('\n')
                    .append('|')
                    .append(percent(artifact.summary().nodes()))
                    .append('\n')
                    .append('|')
                    .append(percent(artifact.summary().edges()))
                    .append('\n')
                    .append('|')
                    .append(percent(artifact.summary().branches()))
                    .append('\n')
                    .append('|')
                    .append(artifact.executionIds().size())
                    .append('\n')
                    .append('|')
                    .append(missingSummary(artifact))
                    .append('\n');
        }
        adoc.append("|===\n\n");
    }

    private void artifactDetails(final StringBuilder adoc, final List<ArtifactReport> artifacts) {
        adoc.append("=== ").append(messages.getString("detailHeading")).append("\n\n");
        for (final var artifact : artifacts) {
            adoc.append("[[")
                    .append(anchor(artifact))
                    .append("]]\n")
                    .append("==== ")
                    .append(text(artifact.artifact().kind()))
                    .append(" - `")
                    .append(text(artifact.artifact().path()))
                    .append("`\n\n")
                    .append(MessageFormat.format(messages.getString("coverageStatus"), status(artifact)))
                    .append(".\n")
                    .append(thresholdLine(artifact))
                    .append(MessageFormat.format(
                            messages.getString("executions"),
                            artifact.executionIds().size()))
                    .append(".\n\n")
                    .append(minisiteHopLinking(artifact))
                    .append("[cols=\"2,1,1,1\",opts=\"headers\"]\n|===\n")
                    .append(messages.getString("summaryHeader"))
                    .append('\n');
            ratio(adoc, messages.getString("metricNodes"), artifact.summary().nodes());
            ratio(adoc, messages.getString("metricEdges"), artifact.summary().edges());
            ratio(adoc, messages.getString("metricBranches"), artifact.summary().branches());
            adoc.append("|===\n\n");
            uncoveredDetails(adoc, artifact);
            nodeDetails(adoc, artifact);
            edgeDetails(adoc, artifact);
        }
    }

    private String thresholdLine(final ArtifactReport artifact) {
        final var required = artifact.requiredCoverage();
        if (required == null) {
            return "";
        }
        return MessageFormat.format(messages.getString("thresholdRequired"), percentValue(required))
                + (overridden(artifact)
                        ? messages.getString("thresholdOverridden")
                        : messages.getString("thresholdGlobal"))
                + "\n";
    }

    private void uncoveredDetails(final StringBuilder adoc, final ArtifactReport artifact) {
        final var missingNodes = artifact.nodes().stream()
                .filter(node -> node.enabled() && !node.covered())
                .sorted(Comparator.comparing(Node::name))
                .toList();
        final var missingEdges = artifact.edges().stream()
                .filter(edge -> edge.enabled() && !edge.covered())
                .sorted(Comparator.comparing(Edge::from).thenComparing(Edge::to))
                .toList();
        adoc.append("===== ")
                .append(messages.getString("uncoveredHeading"))
                .append("\n\n")
                .append("[cols=\"1,4a\",opts=\"headers\"]\n|===\n")
                .append(messages.getString("uncoveredHeader"))
                .append('\n')
                .append("|")
                .append(messages.getString("metricNodes"))
                .append("\n|")
                .append(nodes(missingNodes))
                .append('\n')
                .append("|")
                .append(messages.getString("metricEdges"))
                .append("\n|")
                .append(edges(missingEdges))
                .append('\n')
                .append("|===\n\n");
    }

    private String nodes(final List<Node> nodes) {
        if (nodes.isEmpty()) {
            return messages.getString("none");
        }
        return String.join(
                "\n",
                nodes.stream()
                        .map(node -> "* `" + text(node.name()) + "` (" + text(node.type()) + ")")
                        .toList());
    }

    private String edges(final List<Edge> edges) {
        if (edges.isEmpty()) {
            return messages.getString("none");
        }
        return String.join(
                "\n",
                edges.stream()
                        .map(edge -> "* `" + text(edge.from()) + " -> " + text(edge.to()) + "`"
                                + (edge.kind() == null || edge.kind().isBlank() ? "" : " (" + text(edge.kind()) + ")")
                                + " - " + MessageFormat.format(messages.getString("edgeRows"), edge.rows())
                                + ", "
                                + MessageFormat.format(
                                        messages.getString("edgeTargetExecuted"), yesNo(edge.targetExecuted())))
                        .toList());
    }

    private void nodeDetails(final StringBuilder adoc, final ArtifactReport artifact) {
        adoc.append("===== ")
                .append(messages.getString("metricNodes"))
                .append("\n\n")
                .append("[cols=\"1,3,2,1,1,1,1\",opts=\"headers\"]\n|===\n")
                .append(messages.getString("nodeDetailsHeader"))
                .append('\n');
        artifact.nodes().stream()
                .sorted(Comparator.comparing(Node::name))
                .forEach(node -> adoc.append('|')
                        .append(node.covered() ? "icon:check[role=green] OK" : "icon:times[role=red] KO")
                        .append('\n')
                        .append('|')
                        .append('`')
                        .append(text(node.name()))
                        .append('`')
                        .append('\n')
                        .append('|')
                        .append(text(node.type()))
                        .append('\n')
                        .append('|')
                        .append(node.copies() == null ? "-" : node.copies())
                        .append('\n')
                        .append('|')
                        .append(node.linesRead() + node.linesInput())
                        .append('\n')
                        .append('|')
                        .append(node.linesWritten() + node.linesOutput())
                        .append('\n')
                        .append('|')
                        .append(node.errors())
                        .append('\n'));
        adoc.append("|===\n\n");
    }

    private void edgeDetails(final StringBuilder adoc, final ArtifactReport artifact) {
        adoc.append("===== ")
                .append(messages.getString("metricEdges"))
                .append("\n\n")
                .append("[cols=\"1,3,3,2,1,1,1\",opts=\"headers\"]\n|===\n")
                .append(messages.getString("edgeDetailsHeader"))
                .append('\n');
        artifact.edges().stream()
                .sorted(Comparator.comparing(Edge::from).thenComparing(Edge::to))
                .forEach(edge -> adoc.append('|')
                        .append(edge.covered() ? "icon:check[role=green] OK" : "icon:times[role=red] KO")
                        .append('\n')
                        .append('|')
                        .append('`')
                        .append(text(edge.from()))
                        .append('`')
                        .append('\n')
                        .append('|')
                        .append('`')
                        .append(text(edge.to()))
                        .append('`')
                        .append('\n')
                        .append('|')
                        .append(text(edge.kind() == null ? "hop" : edge.kind()))
                        .append('\n')
                        .append('|')
                        .append(edge.rows())
                        .append('\n')
                        .append('|')
                        .append(yesNo(edge.selected()))
                        .append('\n')
                        .append('|')
                        .append(yesNo(edge.targetExecuted()))
                        .append('\n'));
        adoc.append("|===\n\n");
    }

    private String yesNo(final boolean value) {
        return value ? messages.getString("yes") : messages.getString("no");
    }

    private void ratio(final StringBuilder adoc, final String label, final Ratio ratio) {
        adoc.append('|')
                .append(label)
                .append('\n')
                .append('|')
                .append(percent(ratio))
                .append('\n')
                .append('|')
                .append(ratio.covered())
                .append('\n')
                .append('|')
                .append(ratio.total())
                .append('\n');
    }

    private String status(final ArtifactReport artifact) {
        if (artifact.summary().coverage().ratio() >= effectiveCoverage(artifact)) {
            return "icon:check[role=green] OK";
        }
        return "icon:times[role=red] KO";
    }

    private double effectiveCoverage(final ArtifactReport artifact) {
        final var required = artifact.requiredCoverage();
        return required == null ? expectedCoverage() : required / 100d;
    }

    private boolean overridden(final ArtifactReport artifact) {
        final var required = artifact.requiredCoverage();
        if (required == null) {
            return false;
        }
        final var global = config.requiredCoverage();
        if (global.isEmpty()) {
            return required != DEFAULT_EXPECTED_COVERAGE;
        }
        return required != global.getAsDouble();
    }

    private String missingSummary(final ArtifactReport artifact) {
        final var missingEdges = artifact.edges().stream()
                .filter(edge -> edge.enabled() && !edge.covered())
                .count();
        final var missingNodes = artifact.nodes().stream()
                .filter(node -> node.enabled() && !node.covered())
                .count();
        if (missingEdges == 0 && missingNodes == 0) {
            return "-";
        }
        return MessageFormat.format(messages.getString("missingPattern"), missingEdges, missingNodes);
    }

    private String link(final ArtifactReport artifact) {
        // use xref form that AsciidoctorJ handles reliably (no inline code/backticks inside xref label)
        return "xref:" + anchor(artifact) + "[" + text(artifact.artifact().path()) + "]";
    }

    private String minisiteHopLinking(final ArtifactReport artifact) {
        if (!config.adocReport().enableMinisiteHopLinking()) {
            return "";
        }
        final var name = minisiteName(artifact);
        return messages.getString("documentationHop")
                + " link:hop/" + text(name) + ".html[" + text(name) + "]\n\n"
                + "image::diagrams/" + text(diagramPath(artifact)) + ".svg["
                + MessageFormat.format(messages.getString("diagramAlt"), text(name)) + ",width=900]\n\n";
    }

    private String minisiteName(final ArtifactReport artifact) {
        final var name = artifact.artifact().name();
        final var dot = name.lastIndexOf('.');
        return dot > 0 ? name.substring(0, dot) : name;
    }

    private String diagramPath(final ArtifactReport artifact) {
        final var sourcePath = artifact.artifact().path();
        if (sourcePath == null || sourcePath.isBlank()) {
            return artifact.artifact().name();
        }
        final var path = Path.of(sourcePath);
        final var repository = Path.of("src/main/repositories");
        final var relativePath = path.startsWith(repository) ? repository.relativize(path) : path;
        final var normalized = relativePath.toString().replace('\\', '/');
        final var dot = normalized.lastIndexOf('.');
        return dot > 0 ? normalized.substring(0, dot) : normalized;
    }

    private String anchor(final ArtifactReport artifact) {
        return ("hop-coverage-" + artifact.artifact().kind() + '-'
                        + artifact.artifact().path())
                .replaceAll("[^A-Za-z0-9_-]+", "-");
    }

    private double expectedCoverage() {
        return config.requiredCoverage().orElse(DEFAULT_EXPECTED_COVERAGE) / 100d;
    }

    private String percent(final Ratio ratio) {
        return percentValue(ratio.ratio() * 100);
    }

    private String percentValue(final double value) {
        return String.format(Locale.ROOT, "%.2f%%", value);
    }

    private String text(final String value) {
        if (value == null) {
            return "";
        }
        return value.replace("|", "\\|").replace("\n", " ").replace("\r", " ");
    }
}
